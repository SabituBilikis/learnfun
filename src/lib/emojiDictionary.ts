export function getEmojiName(emoji: string): string {
  if (!emoji) return "item";
  if (EMOJI_NAME_MAP[emoji]) return EMOJI_NAME_MAP[emoji];
  const cleaned = emoji.replace(/[\uFE0F\u200D]/g, "");
  if (EMOJI_NAME_MAP[cleaned]) return EMOJI_NAME_MAP[cleaned];
  if (typeof emoji === "string" && /^[a-z_]+$/i.test(emoji)) {
    return emoji.charAt(0).toUpperCase() + emoji.slice(1);
  }
  return "item";
}
